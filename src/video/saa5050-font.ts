// The SAA5050's character ROM: the dot pattern of each of its 96
// characters, transcribed from the data sheet's character table
// (Signetics "Teletext character generator SAA5050/55", Fig. 11, the
// English set).
//
// Each character is a 5 × 9 dot matrix, drawn in a 6 × 10 cell (Fig. 10).
// Capitals and digits use lines 0-6. Lower case descenders (g j p q y) use
// lines 7-8, which a 5 × 7 terminal font couldn't do.
//
// The pictures below are in the data sheet's order, 8 codes to a block.
// '#' is a dot, '.' is background. Line 0 is the top. They were sampled from
// a high-resolution scan of Fig. 11, one square at a time, and the odd ones
// out (arrows, fractions, £, ÷, the block) checked by eye. This is not a ROM
// dump, and not taken from any emulator.
//
// Codes &00-&1F are control codes (colours, graphics, flash: Stages 32-33).
// They have no shape and display as spaces (Table 1). The SAA5050 has only 7
// data inputs (D1-D7), so bit 7 of a code is ignored: &C1 is A.

