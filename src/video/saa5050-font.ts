/** The font: 128 codes × 9 lines, each 5 bits with bit 4 the leftmost dot. Built once, from PICTURES. */
const GLYPHS: Uint8Array = buildGlyphs();

function buildGlyphs(): Uint8Array {
  const glyphs = new Uint8Array(CODES * GLYPH_ROWS);
  PICTURES.forEach((block, blockIndex) => {
    const lines = block.trim().split('\n').map((line) => line.trim().split(' '));
    if (lines.length !== GLYPH_ROWS) throw new Error(`Font block ${String(blockIndex)} has ${String(lines.length)} lines, not ${String(GLYPH_ROWS)}`);
    lines.forEach((pictures, line) => {
      pictures.forEach((picture, i) => {
        if (!/^[#.]{5}$/.test(picture)) throw new Error(`Font block ${String(blockIndex)}, line ${String(line)}: bad picture "${picture}"`);
        let bits = 0;
        for (const dot of picture) bits = (bits << 1) | (dot === '#' ? 1 : 0);
        glyphs[(FIRST_PRINTABLE + blockIndex * 8 + i) * GLYPH_ROWS + line] = bits;
      });
    });
  });
  return glyphs;
}

/** The 5 dots of one matrix line (0-8) of a character, bit 4 the leftmost. Bit 7 of code is ignored. */
export function glyphRow(code: number, line: number): number {
  return GLYPHS[(code & CODE_MASK) * GLYPH_ROWS + line] ?? 0;
}

/** A character's 9 lines as '#'/'.' pictures, for tests and the CLI. */
export function glyphPicture(code: number): string[] {
  const lines: string[] = [];
  for (let line = 0; line < GLYPH_ROWS; line++) {
    lines.push(glyphRow(code, line).toString(2).padStart(GLYPH_COLUMNS, '0').replace(/0/g, '.').replace(/1/g, '#'));
  }
  return lines;
}

/** The codes where the English SAA5050 doesn't show ASCII (Table 1). */
const NOT_ASCII: ReadonlyMap<number, string> = new Map([
  [0x23, '£'],
  [0x5b, '←'],
  [0x5c, '½'],
  [0x5d, '→'],
  [0x5e, '↑'],
  [0x5f, '#'],
  [0x60, '―'],
  [0x7b, '¼'],
  [0x7c, '‖'],
  [0x7d, '¾'],
  [0x7e, '÷'],
  [0x7f, '■'],
]);

/** What a code shows, as a Unicode character: '£' for &23, a space for a control code. */
export function teletextCharacter(code: number): string {
  const c = code & CODE_MASK;
  if (c < FIRST_PRINTABLE) return ' ';
  return NOT_ASCII.get(c) ?? String.fromCharCode(c);
}
